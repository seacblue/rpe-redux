/**
 * State for the curve inspector, created once per mounted editor tree.
 *
 * A single snapshot carries the form values, the parse error, and the preview
 * flag, so the pane renders from one read. The quick snapshot is the workspace
 * floating panel's read model: the two notes picked by Ctrl+click and the
 * easing the panel may change without opening the full form.
 */
import { createValue, type ValueCell } from "../../../../../core/state/values.ts";
import type { Beat } from "../../../../../core/global/chart/timing/beat.ts";
import type { CurveFieldLabels, CurveFieldValues } from "./CurveFieldsView.tsx";

/** Everything the curve form renders in one snapshot. */
export interface CurveFieldSnapshot {
  labels: CurveFieldLabels;
  values: CurveFieldValues;
  /** The failed parse message, or `null` while the draft is valid. */
  error: string | null;
  /** Whether the generated notes are drawn in the editing area as a ghost. */
  preview: boolean;
  onInput(values: CurveFieldValues): void;
  onPreviewChange(preview: boolean): void;
}

/** One note captured by Ctrl+click, with the line that owns it. */
export interface CurveQuickAnchor {
  startTime: Beat;
  positionX: number;
  lineIndex?: number;
}

/** Whether the quick pick still expects a start, an end, or neither. */
export type CurveQuickPhase = "start" | "end" | "complete";

/** The workspace quick panel's complete read model. */
export interface CurveQuickSnapshot {
  visible: boolean;
  phase: CurveQuickPhase;
  start: CurveQuickAnchor | null;
  end: CurveQuickAnchor | null;
  /** The note type generated by the quick panel; independent of the pane's type. */
  type: number;
  easingType: number;
}

/** The quick panel reads this before any Ctrl+click has started a pick. */
export const EMPTY_CURVE_QUICK: CurveQuickSnapshot = Object.freeze({
  visible: false,
  phase: "start",
  start: null,
  end: null,
  type: 4,
  easingType: 1,
});

/** The curve form's initial values, shared by the editor and its reset actions. */
export const DEFAULT_CURVE_FIELD_VALUES: CurveFieldValues = {
  startTime: [0, 0, 1],
  endTime: [4, 0, 1],
  startX: -405,
  endX: 405,
  density: 1,
  type: 4,
  easingType: 1,
};

export type CurvePickMode = "start" | "end" | null;
export interface CurveState {
  fields: ValueCell<CurveFieldSnapshot | null>;
  pickMode: ValueCell<CurvePickMode>;
  quick: ValueCell<CurveQuickSnapshot>;
}

/** Creates curve inspector state for one mounted editor tree. */
export function createCurveState(): CurveState {
  return {
    fields: createValue<CurveFieldSnapshot | null>({ initial: null }),
    pickMode: createValue<CurvePickMode>({ initial: null }),
    quick: createValue<CurveQuickSnapshot>({ initial: EMPTY_CURVE_QUICK }),
  };
}
