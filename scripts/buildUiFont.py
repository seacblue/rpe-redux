"""
Build the shipped CJK interface font and its on-demand CJK slices.

The UI subset is the first @font-face and is loaded by the editor shell. The
remaining glyphs are split into unicode-range slices; the browser requests only
the slice that contains a character a user actually enters, so arbitrary chart
text keeps the designed face without shipping the full 8 MiB face up front.

`scripts/buildUiFont.mjs` supplies the collected UI text. Requires fontTools
and brotli, the same dependencies as `python -m fontTools.subset`.
"""

import argparse
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

FACE_FAMILY = "Source Han Sans CN"
CHUNK_CODEPOINTS = 2048


def subsetter_options() -> subset.Options:
    """Options matching the documented web subset flags."""
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    options.glyph_names = True
    options.symbol_cmap = True
    options.legacy_cmap = True
    options.notdef_glyph = True
    options.notdef_outline = True
    options.recommended_glyphs = True
    return options


def write_subset(full_font: Path, codepoints: set[int], output: Path) -> None:
    """Write one WOFF2 subset using the web subset flags."""
    font = TTFont(full_font)
    subsetter = subset.Subsetter(options=subsetter_options())
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(output)


def coalesce(codepoints: set[int]) -> list[tuple[int, int]]:
    """Turn a set of codepoints into inclusive ranges for unicode-range."""
    ranges: list[tuple[int, int]] = []
    for codepoint in sorted(codepoints):
        if ranges and codepoint == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], codepoint)
        else:
            ranges.append((codepoint, codepoint))
    return ranges


def unicode_range(ranges: list[tuple[int, int]]) -> str:
    """Format ranges as the CSS unicode-range descriptor."""
    parts = []
    for start, end in ranges:
        parts.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ", ".join(parts)


def face(url: str, ranges: list[tuple[int, int]]) -> str:
    """One @font-face for a shipped slice."""
    return "\n".join(
        [
            "@font-face {",
            f'  font-family: "{FACE_FAMILY}";',
            f'  src: url("{url}") format("woff2");',
            "  font-weight: 400;",
            "  font-style: normal;",
            "  font-display: swap;",
            f"  unicode-range: {unicode_range(ranges)};",
            "}",
        ]
    )


def block_chunks(codepoints: set[int]) -> list[list[int]]:
    """Group codepoints into fixed, size-bounded blocks for lazy loading."""
    blocks: dict[int, list[int]] = {}
    for codepoint in sorted(codepoints):
        blocks.setdefault(codepoint // CHUNK_CODEPOINTS, []).append(codepoint)
    return list(blocks.values())


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--full", required=True, type=Path)
    parser.add_argument("--text", required=True, type=Path)
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--css", required=True, type=Path)
    args = parser.parse_args()

    text = args.text.read_text(encoding="utf-8")
    ui_codepoints = {ord(character) for character in text}
    cmap = TTFont(args.full).getBestCmap()
    font_codepoints = set(cmap)
    ui_codepoints &= font_codepoints

    args.out_dir.mkdir(parents=True, exist_ok=True)
    chunks_dir = args.out_dir / "ui"
    if chunks_dir.exists():
        shutil.rmtree(chunks_dir)
    chunks_dir.mkdir(parents=True, exist_ok=True)

    ui_output = args.out_dir / "SourceHanSansCN-UI.woff2"
    write_subset(args.full, ui_codepoints, ui_output)
    faces = [face("/assets/fonts/SourceHanSansCN-UI.woff2", coalesce(ui_codepoints))]

    remaining = font_codepoints - ui_codepoints
    chunks = block_chunks(remaining)
    for chunk in chunks:
        start, end = chunk[0], chunk[-1]
        name = f"SourceHanSansCN-{start:04X}-{end:04X}.woff2"
        write_subset(args.full, set(chunk), chunks_dir / name)
        faces.append(face(f"/assets/fonts/ui/{name}", [(start, end)]))

    header = [
        "// Generated by scripts/buildUiFont.py. Do not edit by hand.",
        "// Run `npm run build:font` after changing interface or theme text.",
        "// The UI face ships first; each CJK slice loads only when its",
        "// unicode-range is needed by a rendered character.",
        "",
    ]
    args.css.write_text("\n".join(header) + "\n\n".join(faces) + "\n", encoding="utf-8")

    ui_size = ui_output.stat().st_size
    chunk_size = sum(path.stat().st_size for path in chunks_dir.glob("*.woff2"))
    print(
        f"Font slices: UI {ui_size / 1048576:.2f} MiB + "
        f"{len(chunks)} CJK chunks {chunk_size / 1048576:.2f} MiB."
    )


if __name__ == "__main__":
    main()
