/**
 * Compile-time deprecation contract for the public API.
 *
 * TypeScript 7 is the native compiler and exposes no classic AST API, and the
 * repository's ESLint setup parses with Babel rather than typescript-eslint, so
 * `@typescript-eslint/no-deprecated` is unavailable. This script is the
 * equivalent gate:
 *
 * 1. Read `@deprecated` JSDoc from exported facade members under `src/core/api`.
 * 2. Generate `src/core/dev/deprecations.generated.ts` for the runtime detector.
 * 3. Scan non-test source for imports and member access that use those paths.
 *
 * The scan is deliberately conservative: it follows named imports, aliases, and
 * one namespace level. It does not resolve computed property access or values
 * copied through local variables; the runtime guard covers dynamic paths.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "@babel/parser";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const API_ROOT = join(ROOT, "src", "core", "api");
const GENERATED_PATH = join(ROOT, "src", "core", "dev", "deprecations.generated.ts");
const GENERATED_HEADER = `/**
 * Generated by \`scripts/checkDeprecations.mjs\`; do not edit by hand.
 *
 * Each key is a facade path such as \`chart.notes\`; the value is the replacement
 * guidance written in its JSDoc \`@deprecated\` tag.
 */
`;

/** Parse one TypeScript/TSX source file; JSX is enabled only for `.tsx`. */
function parseSource(source, file = "source.ts") {
  const plugins = ["typescript"];
  if (file.endsWith(".tsx")) {
    plugins.push("jsx");
  }
  return parse(source, {
    sourceType: "module",
    plugins,
    errorRecovery: false,
  });
}

/** Walk every AST node without following Babel's comment and token side tables. */
function walk(node, visit) {
  if (!node || typeof node !== "object") {
    return;
  }
  if (Array.isArray(node)) {
    for (const item of node) {
      walk(item, visit);
    }
    return;
  }
  if (typeof node.type === "string") {
    visit(node);
  }
  for (const [key, value] of Object.entries(node)) {
    if (
      key === "loc" ||
      key === "start" ||
      key === "end" ||
      key === "leadingComments" ||
      key === "trailingComments" ||
      key === "innerComments" ||
      key === "extra" ||
      key === "tokens" ||
      key === "comments"
    ) {
      continue;
    }
    walk(value, visit);
  }
}

/** Read the first `@deprecated` tag from a node's leading JSDoc comments. */
export function deprecationMessage(node) {
  for (const comment of node.leadingComments ?? []) {
    const match = /@deprecated\b([\s\S]*?)(?=\n\s*\*\s*@|$)/u.exec(comment.value);
    if (!match) {
      continue;
    }
    const text = match[1]
      .replace(/^\s*\*?\s*/gmu, " ")
      .replace(/\s+/gu, " ")
      .trim();
    return text || "Deprecated.";
  }
  return null;
}

/** Unwrap `Object.freeze({...})` and `expr as const` down to an object literal. */
function objectExpressionOf(node) {
  if (!node) {
    return null;
  }
  if (node.type === "ObjectExpression") {
    return node;
  }
  if (node.type === "TSAsExpression" || node.type === "TSSatisfiesExpression") {
    return objectExpressionOf(node.expression);
  }
  if (
    node.type === "CallExpression" &&
    node.callee?.type === "MemberExpression" &&
    node.callee.object?.type === "Identifier" &&
    node.callee.object.name === "Object" &&
    node.callee.property?.type === "Identifier" &&
    node.callee.property.name === "freeze" &&
    node.arguments.length === 1
  ) {
    return objectExpressionOf(node.arguments[0]);
  }
  return null;
}

/** Return an object member's static name, or null for a computed key. */
function memberName(member) {
  if (!member.computed && member.key?.type === "Identifier") {
    return member.key.name;
  }
  if (member.key?.type === "StringLiteral") {
    return member.key.value;
  }
  return null;
}

/** Collect deprecated object members, descending into nested facade namespaces. */
function collectObjectMembers(object, prefix, entries) {
  for (const member of object.properties) {
    if (member.type !== "ObjectMethod" && member.type !== "ObjectProperty") {
      continue;
    }
    const name = memberName(member);
    if (!name) {
      continue;
    }
    const path = `${prefix}.${name}`;
    const message = deprecationMessage(member);
    if (message) {
      entries.push({ path, message });
    }
    const nested = objectExpressionOf(member.value);
    if (nested) {
      collectObjectMembers(nested, path, entries);
    }
  }
}

/** Extract every deprecated export member from one facade source file. */
export function extractDeprecations(source, file = "source.ts") {
  const ast = parseSource(source, file);
  const entries = [];
  for (const statement of ast.program.body) {
    if (statement.type !== "ExportNamedDeclaration" || !statement.declaration) {
      continue;
    }
    const declaration = statement.declaration;
    if (declaration.type === "VariableDeclaration") {
      for (const declarator of declaration.declarations) {
        if (declarator.id?.type !== "Identifier") {
          continue;
        }
        const owner = declarator.id.name;
        const object = objectExpressionOf(declarator.init);
        if (object) {
          collectObjectMembers(object, owner, entries);
        }
        const message = deprecationMessage(declarator) ?? deprecationMessage(statement);
        if (message) {
          entries.push({ path: owner, message });
        }
      }
      continue;
    }
    if (
      (declaration.type === "FunctionDeclaration" || declaration.type === "ClassDeclaration") &&
      declaration.id
    ) {
      const message = deprecationMessage(declaration) ?? deprecationMessage(statement);
      if (message) {
        entries.push({ path: declaration.id.name, message });
      }
      if (declaration.type === "ClassDeclaration") {
        for (const member of declaration.body.body) {
          const name = memberName(member);
          const memberMessage = deprecationMessage(member);
          if (name && memberMessage) {
            entries.push({ path: `${declaration.id.name}.${name}`, message: memberMessage });
          }
        }
      }
    }
  }
  return entries;
}

/** List every TypeScript file below a directory, sorted for stable output. */
function listSources(directory) {
  const out = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      out.push(...listSources(path));
      continue;
    }
    if (extname(entry.name) === ".ts" || extname(entry.name) === ".tsx") {
      out.push(path);
    }
  }
  return out.sort();
}

/** Build the deprecated map from every public facade module. */
function collectFacadeDeprecations() {
  const entries = new Map();
  for (const file of listSources(API_ROOT)) {
    const source = readFileSync(file, "utf8");
    for (const entry of extractDeprecations(source, file)) {
      entries.set(entry.path, entry.message);
    }
  }
  return entries;
}

/** Quote a string the way Prettier does: prefer double unless it contains more. */
function quoteString(value) {
  const single = value.replace(/\\/gu, "\\\\").replace(/'/gu, "\\'");
  const doubles = (value.match(/"/gu) ?? []).length;
  const singles = (value.match(/'/gu) ?? []).length;
  return doubles > singles ? `'${single}'` : JSON.stringify(value);
}

/** Render the generated runtime registry. */
export function renderGenerated(deprecations) {
  const paths = [...deprecations.keys()].sort();
  const lines = paths.map(
    (path) => `  ${JSON.stringify(path)}: ${quoteString(deprecations.get(path))},`,
  );
  return `${GENERATED_HEADER}export const DEPRECATED_API: Readonly<Record<string, string>> = Object.freeze(${
    lines.length === 0 ? "{}" : `{\n${lines.join("\n")}\n}`
  });\n`;
}

/** Resolve a relative import against the files this repository actually ships. */
function resolveImport(fromFile, specifier) {
  if (!specifier.startsWith(".")) {
    return null;
  }
  const base = resolve(dirname(fromFile), specifier);
  const candidates = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    `${base}.mjs`,
    join(base, "index.ts"),
    join(base, "index.tsx"),
  ];
  for (const candidate of candidates) {
    try {
      readFileSync(candidate);
      return candidate;
    } catch {
      // Try the next extension.
    }
  }
  return null;
}

/** Read every named import and its resolved source file. */
function collectImports(ast, file) {
  const bindings = new Map();
  for (const statement of ast.program.body) {
    if (statement.type !== "ImportDeclaration") {
      continue;
    }
    const sourceFile = resolveImport(file, statement.source.value);
    if (!sourceFile) {
      continue;
    }
    for (const specifier of statement.specifiers) {
      if (specifier.type === "ImportSpecifier") {
        const imported =
          specifier.imported.type === "Identifier"
            ? specifier.imported.name
            : specifier.imported.value;
        bindings.set(specifier.local.name, {
          kind: "named",
          imported,
          sourceFile,
        });
      } else if (specifier.type === "ImportNamespaceSpecifier") {
        bindings.set(specifier.local.name, { kind: "namespace", sourceFile });
      } else if (specifier.type === "ImportDefaultSpecifier") {
        bindings.set(specifier.local.name, { kind: "default", sourceFile });
      }
    }
  }
  return bindings;
}

/** Flatten a static member chain such as `chart.notes` into identifiers. */
function memberChain(node) {
  const chain = [];
  let current = node;
  while (current?.type === "MemberExpression" && !current.computed) {
    if (current.property?.type !== "Identifier") {
      return null;
    }
    chain.unshift(current.property.name);
    current = current.object;
  }
  if (current?.type !== "Identifier") {
    return null;
  }
  chain.unshift(current.name);
  return chain;
}

/** Scan one file for direct use of a deprecated path. */
export function scanDeprecatedUsage(source, file, deprecations, owners) {
  const ast = parseSource(source, file);
  const bindings = collectImports(ast, file);
  const findings = [];
  const seen = new Set();
  const lines = source.split("\n");

  /** Report one hit at the node's start line. */
  const report = (node, path) => {
    const line = node.loc?.start.line ?? 1;
    if (seen.has(`${line}:${path}`) || lines[line - 1]?.includes("deprecated-allow")) {
      return;
    }
    seen.add(`${line}:${path}`);
    findings.push({
      file,
      line,
      column: (node.loc?.start.column ?? 0) + 1,
      path,
      message: deprecations.get(path),
    });
  };

  walk(ast.program, (node) => {
    if (node.type === "MemberExpression") {
      const chain = memberChain(node);
      if (!chain || chain.length < 2) {
        return;
      }
      const [base, ...members] = chain;
      const binding = bindings.get(base);
      if (binding?.kind === "named") {
        const owner = owners.get(`${binding.sourceFile}:${binding.imported}`);
        if (owner) {
          const path = [owner, ...members].join(".");
          if (deprecations.has(path)) {
            report(node, path);
          }
        }
      } else if (binding?.kind === "namespace") {
        const path = members.join(".");
        if (deprecations.has(path)) {
          report(node, path);
        }
      }
      return;
    }
    if (node.type !== "CallExpression" || node.callee.type !== "Identifier") {
      return;
    }
    const binding = bindings.get(node.callee.name);
    if (binding?.kind !== "named") {
      return;
    }
    const path = owners.get(`${binding.sourceFile}:${binding.imported}`) ?? binding.imported;
    if (deprecations.has(path)) {
      report(node, path);
    }
  });

  return findings;
}

/** Run the generated-registry check and the usage scan. */
function main() {
  const write = process.argv.includes("--write");
  const deprecations = collectFacadeDeprecations();
  const generated = renderGenerated(deprecations);
  const current = readFileSync(GENERATED_PATH, "utf8").replace(/\r\n/gu, "\n");
  if (current !== generated) {
    if (write) {
      writeFileSync(GENERATED_PATH, generated);
      console.log(`Wrote ${relative(ROOT, GENERATED_PATH).split(sep).join("/")}`);
    } else {
      console.error(
        "Deprecation registry is stale. Run `npm run generate:deprecations` and commit the result.",
      );
      process.exitCode = 1;
      return;
    }
  }

  const owners = new Map();
  for (const file of listSources(API_ROOT)) {
    for (const entry of extractDeprecations(readFileSync(file, "utf8"), file)) {
      const [owner] = entry.path.split(".");
      owners.set(`${file}:${owner}`, owner);
    }
  }

  const findings = [];
  for (const file of listSources(join(ROOT, "src"))) {
    const relativePath = relative(ROOT, file).split(sep).join("/");
    if (relativePath.startsWith("src/test/") || relativePath.includes("/dev/deprecations")) {
      continue;
    }
    const source = readFileSync(file, "utf8");
    findings.push(...scanDeprecatedUsage(source, file, deprecations, owners));
  }

  if (findings.length > 0) {
    console.error("Deprecated API usage:");
    for (const finding of findings) {
      const path = relative(ROOT, finding.file).split(sep).join("/");
      console.error(`  ${path}:${finding.line}:${finding.column}  ${finding.path}`);
      console.error(`    ${finding.message}`);
    }
    process.exitCode = 1;
    return;
  }
  console.log(
    `Deprecation check passed: ${deprecations.size} deprecated API path(s), no source usage.`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
